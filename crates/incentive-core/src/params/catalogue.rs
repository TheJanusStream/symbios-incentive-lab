//! The catalogue of design levers and world assumptions, in display order.

use super::{ChoiceInfo, ParamGroup, ParamInfo, ParamKind, ParamSide};

const fn range(min: f32, max: f32, step: f32) -> ParamKind {
    ParamKind::Range { min, max, step }
}

const fn design(
    path: &'static str,
    name: &'static str,
    group: ParamGroup,
    kind: ParamKind,
    description: &'static str,
) -> ParamInfo {
    ParamInfo {
        path,
        name,
        description,
        side: ParamSide::Design,
        group,
        kind,
    }
}

const fn world(
    path: &'static str,
    name: &'static str,
    group: ParamGroup,
    kind: ParamKind,
    description: &'static str,
) -> ParamInfo {
    ParamInfo {
        path,
        name,
        description,
        side: ParamSide::World,
        group,
        kind,
    }
}

